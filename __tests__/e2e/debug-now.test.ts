import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`此刻 v3 快照与缺失 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '此刻', exact: true }).click()
    const now = panel.getByTestId('debug-evidence-now')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const toggle = now.getByRole('button', { name: /完整状态/ })
    const detail = now.getByRole('article', { name: '领域证据详情' })
    const chooseEdge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '当前状态边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
      if (await toggle.count() && await toggle.getAttribute('aria-expanded') === 'true') await toggle.click()
    }
    await expect(now.locator('.debug-now-activity')).toHaveText('整理旅行照片')
    await expect(now.locator('.debug-now-activity')).toHaveCSS('font-size', '14px')
    expect(await now.getByRole('combobox', { name: '诊断人物' }).evaluate(node => node.getBoundingClientRect().width)).toBeLessThanOrEqual(180)
    await expect(detail).toHaveCount(0)
    await page.screenshot({ path: info.outputPath('now-v3-default.png') })
    await toggle.click()
    await expect(detail.getByText('65 · 样张值', { exact: true })).toBeVisible()
    await expect(detail.locator('.debug-now-body')).toContainText('不是独立日记')
    await detail.getByRole('button', { name: '查看今日计划', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-schedule').locator('.debug-schedule-row')).toHaveCount(3)
    await expect(panel.getByTestId('debug-evidence-schedule').getByRole('article', { name: '领域证据详情' })).toHaveCount(0)
    await nav.getByRole('button', { name: '此刻', exact: true }).click()
    await now.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(now.getByRole('status')).toContainText('未补造默认世界')
    await expect(now.locator('.debug-now-summary')).toHaveCount(0)
    await now.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    await chooseEdge('paused')
    await expect(now.getByRole('status')).toContainText('生活推进已暂停')
    await toggle.click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(now.getByRole('alert')).toContainText('保留上次快照')
    await expect(now.getByRole('status')).toContainText('生活推进已暂停')
    await expect(detail).toBeVisible()
    await now.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await expect(now.getByRole('status')).toContainText('生活推进已暂停')
    await chooseEdge('fallback')
    await expect(now.getByRole('status')).toContainText('不代表已存世界')
    const warningContrast = await now.locator('.debug-now-warning').evaluate(node => {
      const luminance = (color: string) => {
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / 255).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const foreground = luminance(getComputedStyle(node).color)
      const background = luminance(getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor)
      return (Math.max(foreground, background) + 0.05) / (Math.min(foreground, background) + 0.05)
    })
    expect(warningContrast).toBeGreaterThanOrEqual(4.5)
    await expect(now.locator('.debug-now-activity')).toHaveText('未记录')
    await chooseEdge('unset')
    await expect(now.locator('.debug-now-meta')).toContainText('更新时间未记录')
    await toggle.click()
    await expect(detail).not.toContainText('1970')
    for (const edge of ['unavailable', 'error', 'missing']) {
      await chooseEdge(edge)
      await expect(now.locator('.debug-now-summary')).toHaveCount(0)
      await expect(now.getByRole(edge === 'missing' ? 'status' : 'alert')).toBeVisible()
    }
    await states.getByRole('button', { name: '运行中', exact: true }).click()
    await expect(now.getByRole('status')).toHaveText('正在读取状态…')
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(now.getByRole('combobox')).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(now.getByRole('alert')).toContainText('状态读取失败')
    await expect(now.locator('.debug-now-summary')).toHaveCount(0)
    await now.getByRole('button', { name: '读取状态样张', exact: true }).click()
    await chooseEdge('long')
    await toggle.click()
    await expect(detail.locator('.debug-now-body')).toContainText('补叙长文样张')
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await now.locator('.debug-now-activity').evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('now-v3-long.png') })
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(now.getByRole('status')).toContainText('未补造默认世界')
  })
}
