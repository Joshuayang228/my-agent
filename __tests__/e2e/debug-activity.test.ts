import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`行为日志 v3 来源与阅读 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '行为日志', exact: true }).click()
    const activity = panel.getByTestId('debug-evidence-activity')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const count = activity.getByLabel('行为证据范围计数')
    await expect(activity.getByText('当前读取生活事件；完整行动日志尚未建立。', { exact: true })).toBeVisible()
    await expect(activity.locator('.debug-recent-title')).toHaveText(['河边散步', '阅读旅行笔记', '整理旧书'])
    await expect(activity.locator('[data-record-id="demo-action-tool"]')).toHaveCount(0)
    await expect(activity.locator('.debug-recent-title').first()).toHaveCSS('font-size', '14px')
    await page.screenshot({ path: info.outputPath('activity-v3-default.png') })
    await activity.getByRole('button', { name: '查看调用链', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-traces')).toBeVisible()
    await nav.getByRole('button', { name: '行为日志', exact: true }).click()
    await activity.getByRole('button', { name: '查看成长与反思', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-growth')).toBeVisible()
    await nav.getByRole('button', { name: '行为日志', exact: true }).click()
    const search = activity.getByRole('textbox', { name: '搜索当前页证据' })
    await search.fill('小册子')
    const reading = activity.getByRole('button', { name: '阅读旅行笔记', exact: true })
    await reading.click()
    const detail = activity.getByRole('article', { name: '领域证据详情' })
    await expect(detail.locator('.debug-reading-body')).toBeVisible()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(activity.getByRole('alert')).toContainText('保留上次行为证据')
    await expect(search).toHaveValue('小册子')
    await expect(detail).toBeVisible()
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(reading).toBeFocused()
    await reading.click()
    await detail.getByRole('button', { name: /^查看来源生活事件/ }).click()
    await expect(panel.getByTestId('debug-evidence-recent').getByRole('article', { name: '领域证据详情' })).toContainText('demo-event-reading')
    await nav.getByRole('button', { name: '行为日志', exact: true }).click()
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(activity.getByRole('alert')).toContainText('行为证据读取失败')
    await expect(count).toHaveCount(0)
    await expect(activity.locator('[data-record-id]')).toHaveCount(0)
    await activity.getByRole('button', { name: '读取行为证据样张', exact: true }).click()
    await states.getByText('更多样张', { exact: true }).click()
    await states.getByRole('combobox', { name: '行为证据边缘样张' }).selectOption('paged')
    await states.getByText('更多样张', { exact: true }).click()
    await expect(count).toContainText('2 条已读取')
    await activity.getByRole('button', { name: '读取下一页样张', exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(count).toContainText('3 条已读取')
    await activity.getByRole('button', { name: '重试读取样张', exact: true }).click()
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await activity.locator('.debug-recent-title').first().evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(activity.getByRole('status')).toContainText('此范围没有记录')
    await expect(activity.getByRole('button', { name: '查看调用链', exact: true })).toBeVisible()
  })
}
