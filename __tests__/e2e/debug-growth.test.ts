import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`成长与反思 v3 来源与正文 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    await panel.getByRole('navigation').getByRole('button', { name: '成长与反思', exact: true }).click()
    const growth = panel.getByTestId('debug-evidence-growth')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const detail = growth.getByRole('article', { name: '领域证据详情' })
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '成长边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(detail).toHaveCount(0)
    await expect(growth.locator('[data-record-id]')).toHaveCount(4)
    await expect(growth.locator('.debug-growth-current > .debug-growth-body')).toHaveCSS('font-size', '14px')
    await expect(growth.getByRole('button', { name: '当前成长覆盖', exact: true })).toHaveCSS('font-size', '15px')
    await expect(growth).not.toContainText('冷却中')
    const contrast = await growth.locator('.debug-growth-meta').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / scale).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const color = getComputedStyle(node).color
      const surface = getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor
      const fg = luminance(color), bg = luminance(surface)
      return { color, surface, ratio: (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05) }
    })
    expect(contrast.ratio, JSON.stringify(contrast)).toBeGreaterThanOrEqual(4.5)
    await page.screenshot({ path: info.outputPath('growth-v3-default.png') })
    await growth.getByRole('button', { name: '当前成长覆盖', exact: true }).click()
    await expect(detail.getByRole('heading', { name: '当前成长覆盖', exact: true })).toBeVisible()
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('companion_mutable')
    await expect(detail.locator('pre')).toContainText('demo-role-lin')
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(growth.getByRole('button', { name: '当前成长覆盖', exact: true })).toBeFocused()
    await growth.getByRole('button', { name: '反思运行结果', exact: true }).click()
    await expect(detail).toContainText('不是隐藏思维')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('companion_reflection_state')
    await expect(detail.locator('pre')).toContainText('demo-role-lin')
    await growth.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(detail).toHaveCount(0)
    await expect(growth.locator('.debug-growth-current')).toContainText('不是用户覆盖')
    await expect(growth.locator('.debug-growth-current')).not.toContainText('v1')
    await growth.getByRole('button', { name: '已读默认成长定义', exact: true }).click()
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('Role Pack mutable.default')
    await expect(detail.getByRole('button', { name: /查看当前注册定义/ })).toHaveCount(0)
    await growth.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    await edge('reflection-error')
    await expect(growth).toContainText('结果数量未知')
    await expect(growth.getByRole('button', { name: '当前成长覆盖', exact: true })).toBeVisible()
    await expect(growth.getByRole('button', { name: '历史版本 v2', exact: true })).toBeVisible()
    await expect(growth).not.toContainText('当前已读范围没有反思状态')
    await edge('empty-body')
    await expect(growth.locator('.debug-growth-current')).toContainText('未改用默认正文')
    await edge('unknown-time')
    await expect(growth.locator('.debug-growth-current')).toContainText('未记录')
    await expect(growth).not.toContainText('1970')
    await edge('paged')
    await expect(growth.locator('.debug-growth-history')).toContainText('1 项已读历史')
    await growth.getByRole('button', { name: '读取下一页历史样张', exact: true }).click()
    await expect(growth.locator('.debug-growth-history')).toContainText('2 项已读历史')
    await growth.getByRole('button', { name: '历史版本 v1', exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(detail.getByRole('heading', { name: '历史版本 v1', exact: true })).toBeVisible()
    await expect(growth.locator('.debug-growth-history')).toContainText('2 项已读历史')
    await growth.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await expect(growth.getByRole('button', { name: '读取下一页历史样张', exact: true })).toHaveCount(0)
    await growth.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(growth.getByRole('button', { name: '读取下一页历史样张', exact: true })).toHaveCount(0)
    await growth.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(growth.locator('[data-record-id]')).toHaveCount(0)
      await expect(growth).not.toContainText('项已读历史')
    }
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(growth.getByRole('combobox', { name: '诊断人物' })).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(growth.getByRole('alert')).toContainText('成长资料读取失败')
    await growth.getByRole('button', { name: '读取成长样张', exact: true }).click()
    await edge('missing')
    await expect(detail).toHaveCount(0)
    await expect(growth.getByRole('status')).toContainText('未选择替代记录')
    await edge('long')
    await growth.getByRole('button', { name: '当前成长覆盖', exact: true }).click()
    const body = await detail.locator(':scope > .debug-growth-body').innerText()
    expect(body.length).toBeGreaterThan(400)
    expect(body.length).toBeLessThanOrEqual(800)
    expect((await growth.locator('.debug-growth-current > .debug-growth-body').innerText()).length).toBeLessThanOrEqual(181)
    await growth.getByRole('button', { name: '历史版本 v2', exact: true }).click()
    await expect(detail.locator(':scope > .debug-growth-body')).toHaveText(body)
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await detail.locator('.debug-growth-body').evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('growth-v3-long.png') })
    await states.getByRole('button', { name: '默认记录', exact: true }).click()
    await growth.getByRole('button', { name: '当前成长覆盖', exact: true }).click()
    await detail.getByRole('button', { name: '查看稳定人物定义', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-character')).toBeVisible()
    await expect(panel.getByTestId('debug-evidence-character').getByRole('article', { name: '领域证据详情' })).toHaveCount(0)
    await panel.getByRole('navigation').getByRole('button', { name: '成长与反思', exact: true }).click()
    await growth.getByRole('button', { name: '当前成长覆盖', exact: true }).click()
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await detail.getByRole('button', { name: '查看当前注册定义 · demo.prompt.growth', exact: true }).click()
    await expect(panel.getByRole('article', { name: '资产详情' })).toContainText('成长覆盖 · 林')
    await panel.getByRole('navigation').getByRole('button', { name: '成长与反思', exact: true }).click()
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(growth.getByRole('status')).toContainText('未补默认正文')
    await expect(growth.locator('[data-record-id]')).toHaveCount(0)
  })
}
