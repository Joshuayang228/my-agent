import { test, expect } from '@playwright/test'
for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`用户画像 v3 来源摘要 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    await panel.getByRole('navigation').getByRole('button', { name: '用户画像', exact: true }).click()
    const profile = panel.getByTestId('debug-evidence-profile')
    await expect(profile).toContainText('全局资料与当前人物的协作反馈')
    expect(await profile.locator('.debug-profile-toolbar label').evaluate(node => { const range = document.createRange(); range.selectNodeContents(node.firstChild!); return range.getClientRects().length })).toBe(1)
    await expect(profile).toContainText('不是全量画像')
    await expect(profile.getByRole('heading', { name: '身份', exact: true })).toBeVisible()
    await expect(profile.getByRole('heading', { name: '协作方式', exact: true })).toBeVisible()
    await expect(profile.getByRole('heading', { name: '表达偏好', exact: true })).toBeVisible()
    await expect(profile.locator('[data-record-id="demo-feedback-yu"]')).toHaveCount(0)
    await expect(profile.locator('.debug-profile-body')).toHaveCount(0)
    await page.screenshot({ path: info.outputPath('profile-v3-default.png') })
    await profile.locator('[data-record-id="demo-profile-identity"] button').click()
    await profile.locator('.debug-profile-detail .debug-profile-source summary').click(); await expect(profile.getByRole('article', { name: '画像来源详情' })).toContainText('保存桶')
    await expect(profile.getByRole('article', { name: '画像来源详情' })).toContainText('demo-profile-identity')
    await profile.getByRole('button', { name: '返回摘要', exact: true }).click()
    await expect(profile.locator('[data-record-id="demo-profile-identity"] button')).toBeFocused()
    await profile.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(profile.locator('[data-record-id="demo-feedback-yu"]')).toBeVisible()
    await profile.locator('[data-record-id="demo-feedback-yu"] button').click()
    await expect(profile.getByRole('article', { name: '画像来源详情' })).toContainText('当前人物反馈 · yu')
    await profile.getByText('查询范围与其他入口', { exact: true }).click()
    await expect(profile).toContainText('当前页 7 条已读来源')
    await profile.getByRole('button', { name: '查看请求保存范围', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-context')).toBeVisible()
    await panel.getByRole('navigation').getByRole('button', { name: '用户画像', exact: true }).click()
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    await states.getByText('更多样张', { exact: true }).click()
    const select = states.getByRole('combobox', { name: '画像边缘样张' })
    await select.selectOption('partial'); await states.getByText('更多样张', { exact: true }).click()
    await expect(profile).toContainText('部分来源未返回')
    await states.getByText('更多样张', { exact: true }).click(); await select.selectOption('long'); await states.getByText('更多样张', { exact: true }).click()
    await profile.locator('[data-record-id="demo-memory-lin"] button').click()
    await expect(profile.getByRole('article', { name: '画像来源详情' })).toContainText('长反馈样张')
    await states.getByText('更多样张', { exact: true }).click(); await select.selectOption('unknown-time'); await states.getByText('更多样张', { exact: true }).click()
    await expect(profile.getByRole('article', { name: '画像来源详情' })).toContainText('未记录')
    await states.getByText('更多样张', { exact: true }).click(); await select.selectOption('paged'); await states.getByText('更多样张', { exact: true }).click()
    await expect(profile.getByRole('button', { name: '读取下一页来源样张', exact: true })).toBeVisible()
    await profile.getByRole('button', { name: '读取下一页来源样张', exact: true }).click()
    await expect(profile.locator('[data-record-id]')).toHaveCount(7)
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(profile).toContainText('刷新失败，保留原人物')
    expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('profile-v3-long.png') })
  })
}
