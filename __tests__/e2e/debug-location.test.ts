import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`当前位置 v3 阅读与回退 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '当前位置', exact: true }).click()
    const location = panel.getByTestId('debug-evidence-location')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const toggle = location.getByRole('button', { name: /完整快照/ })
    const detail = location.getByRole('article', { name: '领域证据详情' })
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '位置边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
      if (await toggle.count() && await toggle.getAttribute('aria-expanded') === 'true') await toggle.click()
    }
    await expect(location.locator('.debug-location-place')).toHaveText('样张书房')
    await expect(location.locator('.debug-location-place')).toHaveCSS('font-size', '14px')
    await expect(location.locator('.debug-location-body')).toHaveText('书桌前')
    await expect(detail).toHaveCount(0)
    expect(await location.getByRole('combobox').evaluate(node => node.getBoundingClientRect().width)).toBeLessThanOrEqual(180)
    await page.screenshot({ path: info.outputPath('location-v3-default.png') })
    await toggle.focus()
    await page.keyboard.press('Enter')
    await expect(detail).toContainText('更新时间不是到达时间')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('currentLocation')
    await detail.getByRole('button', { name: /查看注册定义/ }).click()
    await expect(panel).toHaveAttribute('data-perspective', 'assets')
    await expect(panel).toContainText('demo.world.lin')
    for (const [label, destination] of [['查看家居资料', 'residence'], ['查看足迹记录', 'footprints']]) {
      await nav.getByRole('button', { name: '当前位置', exact: true }).click()
      await toggle.click()
      await detail.getByRole('button', { name: label, exact: true }).click()
      await expect(panel.getByTestId(`debug-evidence-${destination}`).getByRole('article', { name: '领域证据详情' })).toHaveCount(0)
    }
    await nav.getByRole('button', { name: '当前位置', exact: true }).click()
    await location.getByRole('combobox').selectOption('yu')
    await expect(location.getByRole('status')).toContainText('未补造默认地点')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(location.getByRole('combobox')).toHaveValue('yu')
    await expect(location.getByRole('alert')).toContainText('保留上次位置快照')
    await expect(location.locator('[data-record-id]')).toHaveCount(0)
    await location.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await location.getByRole('combobox').selectOption('lin')
    await edge('fallback')
    await expect(location.getByRole('status')).toContainText('不代表实际位置已知')
    const contrast = await location.locator('.debug-location-warning').evaluate(node => {
      const luminance = (color: string) => {
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / 255).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const foreground = luminance(getComputedStyle(node).color)
      const background = luminance(getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor)
      return (Math.max(foreground, background) + 0.05) / (Math.min(foreground, background) + 0.05)
    })
    expect(contrast).toBeGreaterThanOrEqual(4.5)
    await toggle.click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(detail).toBeVisible()
    await expect(location.getByRole('status')).toContainText('不代表实际位置已知')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('旧结构地点')
    await page.screenshot({ path: info.outputPath('location-v3-fallback.png') })
    await edge('unset')
    await expect(location.locator('.debug-location-meta')).toContainText(['位置细节未记录', '世界更新时间未记录'])
    await toggle.click()
    await expect(detail).not.toContainText('1970')
    for (const value of ['unavailable', 'error', 'missing']) {
      await edge(value)
      await expect(location.locator('[data-record-id]')).toHaveCount(0)
      await expect(location.getByRole(value === 'missing' ? 'status' : 'alert')).toBeVisible()
    }
    await states.getByRole('button', { name: '运行中', exact: true }).click()
    await expect(location.getByRole('status')).toHaveText('正在读取位置…')
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(location.getByRole('combobox')).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(location.getByRole('alert')).toContainText('位置读取失败')
    await expect(location.locator('[data-record-id]')).toHaveCount(0)
    await location.getByRole('button', { name: '读取位置样张', exact: true }).click()
    await edge('long')
    expect((await location.locator('.debug-location-place').innerText()).length).toBeLessThanOrEqual(40)
    expect((await location.locator('.debug-location-body').innerText()).length).toBeLessThanOrEqual(80)
    await toggle.click()
    await detail.getByText('来源与原始样张', { exact: true }).click()
    expect((await detail.locator('pre').innerText()).length).toBeGreaterThan(1000)
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(detail).toBeVisible()
    await expect(detail).toContainText('长位置细节样张')
    await expect(detail.locator('pre')).toContainText('长位置细节样张')
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await location.locator('.debug-location-place').evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('location-v3-long.png') })
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(location.getByRole('status')).toContainText('未补造默认地点')
  })
}
