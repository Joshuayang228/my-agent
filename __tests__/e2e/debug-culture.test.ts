import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`文化角 v3 状态与笔记 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '文化角', exact: true }).click()
    const culture = panel.getByTestId('debug-evidence-items')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const detail = culture.getByRole('article', { name: '领域证据详情' })
    const search = culture.getByRole('textbox', { name: '搜索当前页证据' })
    const book = culture.locator('[data-record-id="demo-item-book"]').getByRole('button')
    const tabs = culture.getByRole('tablist', { name: '文化分类' })
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '文化边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(detail).toHaveCount(0)
    await expect(culture.locator('[data-record-id]')).toHaveCount(4)
    await expect(book).toHaveCSS('font-size', '14px')
    await expect(tabs.getByRole('tab', { name: '音乐', exact: true })).toHaveCSS('font-size', '13px')
    await expect(tabs.getByRole('tab', { name: '音乐', exact: true })).toHaveCSS('color', await culture.locator('.debug-culture-meta').first().evaluate(node => getComputedStyle(node).color))
    const contrast = await culture.locator('.debug-culture-meta').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / scale).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const color = getComputedStyle(node).color
      const surface = getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor
      const fg = luminance(color), bg = luminance(surface)
      return { color, surface, ratio: (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05) }
    })
    expect(contrast.ratio, JSON.stringify(contrast)).toBeGreaterThanOrEqual(4.5)
    await page.screenshot({ path: info.outputPath('culture-v3-default.png') })
    await book.click()
    await expect(detail.locator('[data-note-id]')).toHaveCount(2)
    await expect(detail.locator('[data-note-id="demo-reading-note-river"]')).toContainText('发生时间：2026/10/13 14:30')
    await expect(detail.locator('[data-note-id="demo-reading-note-margin"]')).toContainText('创建时间：2026/10/12 16:00')
    await expect(detail.locator(':scope > .debug-culture-body')).toContainText('作品说明样张')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('demo-reading-note-river')
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(book).toBeFocused()
    await edge('paged')
    await tabs.getByRole('tab', { name: '音乐', exact: true }).click()
    await expect(culture.getByRole('status')).toContainText('没有匹配的文化记录')
    await culture.getByRole('button', { name: '读取下一页文化样张', exact: true }).click()
    await expect(culture.locator('.debug-culture-range')).toContainText('1 项匹配 · 4 项已读作品')
    await culture.getByRole('button', { name: '午后旋律', exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(tabs.getByRole('tab', { name: '音乐', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(detail.locator(':scope > .debug-culture-body')).toContainText('听感样张')
    await culture.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await expect(culture.getByRole('button', { name: '读取下一页文化样张', exact: true })).toHaveCount(0)
    await tabs.getByRole('tab', { name: '全部', exact: true }).click()
    await search.fill('车票')
    await expect(culture.locator('[data-record-id]')).toHaveCount(1)
    await book.click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(search).toHaveValue('车票')
    await expect(detail).toBeVisible()
    await culture.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await search.fill('')
    await edge('empty-notes')
    await book.click()
    await expect(detail.locator('.debug-culture-notes')).toContainText('未回退旧笔记')
    await expect(detail.locator('[data-note-id]')).toHaveCount(0)
    await expect(detail.locator('.debug-culture-notes')).not.toContainText('不应复活的旧笔记')
    await edge('legacy-note')
    await expect(detail.locator('[data-note-id="demo-item-book:note"]')).toContainText('笔记时间：未记录')
    await edge('invalid-notes')
    await expect(detail.locator('.debug-culture-notes')).toContainText('笔记结构无效')
    await expect(detail.locator('[data-note-id]')).toHaveCount(0)
    await edge('invalid-progress')
    await expect(detail).toContainText('当前进度不能超过总量')
    await edge('missing-fields')
    await expect(culture.locator('[data-record-id="demo-item-book"]')).toContainText('状态未记录')
    await expect(detail.locator('.debug-culture-notes')).toContainText('笔记时间：未记录')
    await expect(detail.locator('.debug-culture-notes')).not.toContainText('1970')
    await edge('archived')
    await expect(culture.locator('[data-record-id]')).toHaveCount(4)
    await expect(culture.locator('[data-record-id="demo-culture-music"]')).toContainText('已归档记录')
    await edge('unknown')
    await tabs.getByRole('tab', { name: '未识别', exact: true }).click()
    await expect(culture.locator('[data-record-id]')).toHaveCount(1)
    await tabs.getByRole('tab', { name: '全部', exact: true }).click()
    await edge('truncated')
    await book.click()
    await expect(detail).toContainText('不能认定为完整作品与笔记')
    await culture.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(culture.getByRole('status')).toContainText('不推断没有兴趣')
    await culture.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(culture.locator('[data-record-id]')).toHaveCount(0)
      await expect(culture.locator('.debug-culture-range')).toHaveCount(0)
    }
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(search).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(culture.getByRole('alert')).toContainText('文化资料读取失败')
    await culture.getByRole('button', { name: '读取文化样张', exact: true }).click()
    await edge('missing')
    await expect(detail).toHaveCount(0)
    await expect(culture.getByRole('status')).toContainText('未选择替代记录')
    await edge('long')
    await book.click()
    expect((await book.innerText()).length).toBeLessThanOrEqual(160)
    expect((await detail.locator(':scope > .debug-culture-body').innerText()).length).toBeGreaterThan(1000)
    const longNote = detail.locator('[data-note-id] .debug-culture-body')
    expect((await longNote.innerText()).length).toBeGreaterThan(1000)
    expect((await longNote.innerText()).length).toBeLessThanOrEqual(4000)
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await longNote.evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('culture-v3-long.png') })
    await states.getByRole('button', { name: '默认记录', exact: true }).click()
    await book.click()
    await detail.getByRole('button', { name: '查看来源事件', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-recent').getByRole('article', { name: '领域证据详情' })).toContainText('没有完成证据')
    await nav.getByRole('button', { name: '文化角', exact: true }).click()
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(culture.getByRole('status')).toContainText('当前查询未返回文化记录')
  })
}
