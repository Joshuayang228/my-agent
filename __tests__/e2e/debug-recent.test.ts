import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`最近事项 v3 阅读与快照 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    await panel.getByRole('navigation').getByRole('button', { name: '最近事项', exact: true }).click()
    const recent = panel.getByTestId('debug-evidence-recent')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const search = recent.getByRole('textbox', { name: '搜索当前页证据' })
    const date = recent.getByRole('textbox', { name: '证据日期' })
    const count = recent.getByLabel('事项范围计数')
    const detail = recent.getByRole('article', { name: '领域证据详情' })
    const chooseEdge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '事项边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(date).toHaveValue('')
    await expect(count).toHaveText('3 条已读取 · 总数未知')
    await expect(recent.locator('.debug-recent-title')).toHaveText(['河边散步', '阅读旅行笔记', '整理旧书'])
    await expect(recent.locator('.debug-recent-title').first()).toHaveCSS('font-size', '14px')
    await expect(recent.getByText(/翻到上次旅途/)).toHaveCount(0)
    await page.screenshot({ path: info.outputPath('recent-v3-default.png') })
    await search.fill('小册子')
    const reading = recent.getByRole('button', { name: '阅读旅行笔记', exact: true })
    await expect(count).toContainText('1 条匹配')
    await reading.click()
    await expect(detail.locator('.debug-reading-body')).toBeVisible()
    await expect(detail.locator('.debug-reading-body')).toContainText('翻到上次旅途')
    await expect(detail.getByText('published · 已发布', { exact: true })).toBeHidden()
    await detail.getByText('完整字段', { exact: true }).click()
    await expect(detail.getByText('published · 已发布', { exact: true })).toBeVisible()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(recent.getByRole('alert')).toContainText('保留上次事项')
    await expect(search).toHaveValue('小册子')
    await expect(detail.getByText('published · 已发布', { exact: true })).toBeVisible()
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(reading).toBeFocused()
    await recent.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await search.fill('不存在的事项')
    await expect(recent.getByRole('status')).toContainText('没有匹配的证据')
    await search.fill('')
    await date.fill('2026-10-12')
    await expect(recent.locator('.debug-recent-title')).toHaveText(['整理旧书'])
    await recent.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(recent.getByRole('status')).toContainText('此范围没有记录')
    await recent.getByRole('button', { name: '清除筛选', exact: true }).click()
    await states.getByRole('button', { name: '运行中', exact: true }).click()
    await expect(recent.getByRole('status')).toContainText('正在读取事项')
    await expect(count).toHaveCount(0)
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(count).toHaveCount(0)
    await expect(search).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(recent.getByRole('alert')).toContainText('事项读取失败')
    await expect(recent.locator('[data-record-id]')).toHaveCount(0)
    await recent.getByRole('button', { name: '读取事项样张', exact: true }).click()
    for (const edge of ['unavailable', 'error', 'missing']) {
      await chooseEdge(edge)
      await expect(recent.getByRole(edge === 'missing' ? 'status' : 'alert')).toBeVisible()
      await expect(detail).toHaveCount(0)
    }
    await chooseEdge('unknown-time')
    await expect(recent.locator('.debug-recent-time').last()).toHaveText('时间未记录')
    await chooseEdge('paged')
    await expect(count).toContainText('2 条已读取')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(count).toContainText('2 条已读取')
    await recent.getByRole('button', { name: '读取下一页样张', exact: true }).click()
    await expect(count).toContainText('3 条已读取')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(count).toContainText('3 条已读取')
    await recent.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await chooseEdge('long')
    await recent.getByRole('button', { name: /整理一段较长的旅行见闻/ }).click()
    await expect(detail.locator('.debug-reading-body')).toContainText('长正文样张')
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await detail.locator('.debug-reading-body').evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('recent-v3-long.png') })
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(count).toHaveText('0 条已读取 · 总数未知')
    await expect(recent.getByRole('status')).toContainText('此范围没有记录')
    await states.getByRole('button', { name: '历史截断', exact: true }).click()
    await expect(panel.getByRole('status').filter({ hasText: '历史已截断' })).toBeVisible()
  })
}
