import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`衣柜 v3 状态与引用 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '衣柜', exact: true }).click()
    const wardrobe = panel.getByTestId('debug-evidence-wardrobe')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const detail = wardrobe.getByRole('article', { name: '领域证据详情' })
    const search = wardrobe.getByRole('textbox', { name: '搜索当前页证据' })
    const coat = wardrobe.locator('[data-record-id="demo-wardrobe-coat"]').getByRole('button')
    const outfit = wardrobe.locator('[data-record-id="demo-wardrobe-outfit"]').getByRole('button')
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '衣柜边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(detail).toHaveCount(0)
    await expect(wardrobe.locator('[data-record-id]')).toHaveCount(6)
    await expect(wardrobe.locator('[data-wardrobe-group="garment"] [data-record-id]')).toHaveCount(4)
    await expect(coat).toHaveCSS('font-size', '14px')
    await expect(wardrobe.locator('[data-record-id="demo-wardrobe-shirt"]')).not.toContainText('版本')
    await expect(coat).toHaveCSS('color', await wardrobe.evaluate(node => getComputedStyle(node).color))
    const contrast = await wardrobe.locator('.debug-wardrobe-meta').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / scale).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const color = getComputedStyle(node).color
      const surface = getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor
      const fg = luminance(color), bg = luminance(surface)
      return { color, surface, ratio: (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05) }
    })
    expect(contrast.ratio, JSON.stringify(contrast)).toBeGreaterThanOrEqual(4.5)
    await page.screenshot({ path: info.outputPath('wardrobe-v3-default.png') })
    await outfit.click()
    await expect(detail.locator('.debug-wardrobe-slots > div')).toHaveCount(4)
    await detail.locator('.debug-wardrobe-slots').getByRole('button', { name: '浅色衬衫', exact: true }).click()
    await expect(detail.getByRole('heading', { name: '浅色衬衫', exact: true })).toBeVisible()
    await expect(detail).toContainText('旧单件样张')
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(wardrobe.getByRole('button', { name: '浅色衬衫', exact: true })).toBeFocused()
    await edge('paged')
    await expect(wardrobe.getByRole('status')).toContainText('未包含穿搭状态')
    await expect(wardrobe.locator('[data-record-id]')).toHaveCount(2)
    await search.fill('出行套装')
    await wardrobe.getByRole('button', { name: '读取下一页衣柜样张', exact: true }).click()
    await expect(wardrobe.locator('.debug-wardrobe-range')).toContainText('1 项匹配 · 6 项已读记录')
    await outfit.click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(search).toHaveValue('出行套装')
    await expect(detail.getByRole('heading', { name: '出行套装', exact: true })).toBeVisible()
    await wardrobe.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await expect(wardrobe.getByRole('button', { name: '读取下一页衣柜样张', exact: true })).toHaveCount(0)
    await search.fill('')
    await edge('unread-reference')
    await outfit.click()
    await expect(detail.locator('.debug-wardrobe-slots')).toContainText('不能判定不存在')
    await edge('mismatch')
    await expect(detail.locator('.debug-wardrobe-slots')).toContainText('分类与槽位不匹配')
    await edge('invalid')
    await expect(detail).toContainText('穿搭需要有效衣物槽位')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('"slots": {}')
    await edge('conflict')
    await expect(wardrobe.getByRole('status')).toContainText('不推断哪条生效')
    await expect(wardrobe.locator('[data-wardrobe-group="wear-state"] [data-record-id]')).toHaveCount(2)
    await edge('unknown')
    await expect(wardrobe.locator('[data-wardrobe-group="unknown"] [data-record-id]')).toHaveCount(1)
    await edge('unknown-time')
    await wardrobe.getByRole('button', { name: '当前穿搭', exact: true }).click()
    await detail.getByText('完整字段', { exact: true }).click()
    await expect(detail.locator('.debug-candidate-facts')).toContainText('收录时间未记录')
    await expect(detail).not.toContainText('1970')
    await edge('truncated')
    await expect(detail).toContainText('记录存在截断')
    await wardrobe.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(wardrobe.getByRole('status')).toContainText('不推断没有衣物')
    await expect(wardrobe.getByRole('button', { name: '读取下一页衣柜样张', exact: true })).toHaveCount(0)
    await wardrobe.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(wardrobe.locator('[data-record-id]')).toHaveCount(0)
      await expect(wardrobe.locator('.debug-wardrobe-range')).toHaveCount(0)
    }
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(search).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(wardrobe.getByRole('alert')).toContainText('衣柜读取失败')
    await wardrobe.getByRole('button', { name: '读取衣柜样张', exact: true }).click()
    await edge('missing')
    await expect(detail).toHaveCount(0)
    await expect(wardrobe.getByRole('status')).toContainText('未选择替代记录')
    await edge('long')
    await coat.click()
    expect((await coat.innerText()).length).toBeLessThanOrEqual(160)
    expect((await detail.locator('.debug-wardrobe-body').innerText()).length).toBeGreaterThan(1000)
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await detail.locator('.debug-wardrobe-body').evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('wardrobe-v3-long.png') })
    await states.getByRole('button', { name: '默认记录', exact: true }).click()
    await coat.click()
    await detail.getByRole('button', { name: '查看来源事件', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-recent').getByRole('article', { name: '领域证据详情' })).toContainText('没有完成证据')
    await nav.getByRole('button', { name: '衣柜', exact: true }).click()
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(wardrobe.getByRole('status')).toContainText('当前查询未返回衣柜记录')
  })
}
