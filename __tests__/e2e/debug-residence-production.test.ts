import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`正式家居层级与分页 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.addInitScript(theme => localStorage.setItem('theme', theme), theme)
    await page.goto('/')
    await page.evaluate(() => {
      const state = window as unknown as { electronAPI: { debug: Record<string, unknown> }; __homeMode: string; __homeQueries: Array<{ view: string; cursor?: string; recordId?: string }> }
      state.electronAPI = { ...state.electronAPI, debug: { ...state.electronAPI?.debug } }
      state.__homeMode = 'fail'; state.__homeQueries = []
      Object.assign(state.electronAPI.debug, {
        companionEvidenceScope: async () => ({ roles: [{ id: 'lin', name: '林' }, { id: 'yu', name: '予' }], activeRoleId: 'lin', universeId: 'test', ready: true }),
        companionEvidenceQuery: async (query: { view: string; roleId: string; cursor?: string; recordId?: string }) => {
          state.__homeQueries.push(query)
          if (state.__homeMode === 'fail') throw new Error('home contract failure')
          const record = (id: string, kind: string, title: string, payload: Record<string, unknown>, links: Array<{ view: string; id: string; label: string }> = []) => ({ id, roleId: query.roleId, kind, title, body: '', source: 'companion_assets', time: null, status: '', truncated: false, links, data: { payload, acquired_at: Date.parse('2026-10-25T06:00:00Z') } })
          const rows = [record('home', 'home', '住所记录', { recordType: 'residence', description: state.__homeMode === 'long' ? '家居长描述。'.repeat(200) : '真实住所描述' }), record('space', 'home', '书房空间', { recordType: 'space', residenceId: 'home' }), record('camera', 'furniture', '小相机', { spaceId: state.__homeMode === 'orphan' ? 'absent' : 'space', displayInHome: true, displayReason: '整理照片时展示', description: '相机描述', displayEvidence: ['event-real'] }, [{ view: 'recent', id: 'event-real', label: '来源生活事件' }]), record('box', 'furniture', '备用收纳盒', { displayInHome: false }), record('unknown', 'home', '旧类型记录', { recordType: 'legacy', savedField: '未知原文字段' }), record('wrong', 'furniture', '错误归属物件', { spaceId: 'home', displayInHome: 'true' })]
          const records = query.roleId === 'yu' ? [] : query.view === 'recent' ? [{ ...record('event-real', 'reading', '来源事件', {}), source: 'companion_events', body: '来源事件正文', data: { scheduled_at: Date.parse('2026-10-25T06:00:00Z') } }] : query.view !== 'residence' ? [] : query.recordId ? rows.filter(row => row.id === query.recordId) : query.cursor ? rows.slice(2) : rows.slice(0, 2)
          const hasMore = query.view === 'residence' && !query.recordId && !query.cursor && query.roleId === 'lin'
          return { ...query, state: 'ready', source: query.view === 'recent' ? 'companion_events' : 'companion_assets', timezone: 'Asia/Shanghai', total: null, generatedAt: Date.now(), records, hasMore, nextCursor: hasMore ? 'next' : undefined, issues: [], boundary: '只读已读范围，不补造住所' }
        },
      })
    })
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Debug', exact: true }).click()
    const panel = page.getByTestId('dev-panel')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '家居', exact: true }).click()
    const home = panel.getByTestId('debug-evidence-residence')
    const search = home.getByRole('textbox', { name: '搜索当前页证据' })
    const detail = home.getByRole('article', { name: '领域证据详情' })
    await expect(home.getByRole('alert')).toContainText('读取失败')
    await expect(home.locator('.debug-home-range')).toHaveCount(0)
    await page.evaluate(() => { (window as unknown as { __homeMode: string }).__homeMode = 'ready' })
    await home.getByRole('button', { name: '重试', exact: true }).click()
    await expect(home.locator('.debug-home-range')).toHaveText('2 项已读 · 总数未知')
    await expect(home.locator('.debug-home-space [data-record-id="space"]')).toBeVisible()
    await search.fill('小相机')
    await expect(home).toContainText('没有匹配的家居资料')
    await home.getByRole('button', { name: '读取下一页', exact: true }).click()
    await expect(home.locator('.debug-home-range')).toHaveText('1 项匹配 · 6 项已读 · 总数未知')
    await expect(home.locator('.debug-home-meta')).toContainText('归属：书房空间')
    const camera = home.getByRole('button', { name: '小相机', exact: true })
    await camera.click()
    await expect(detail.locator('.debug-home-body')).toHaveText(['相机描述', '整理照片时展示'])
    await detail.getByText('完整字段', { exact: true }).click()
    await expect(detail).toContainText('displayInHome = true')
    await detail.getByText('来源与原始记录', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('event-real')
    await page.evaluate(() => { (window as unknown as { __homeMode: string }).__homeMode = 'fail' })
    await panel.getByRole('button', { name: '刷新当前分区', exact: true }).click()
    await expect(home.getByRole('alert')).toContainText('保留上次资产与已加载页')
    await expect(detail.locator('pre')).toBeVisible()
    await page.evaluate(() => { (window as unknown as { __homeMode: string }).__homeMode = 'ready' })
    await home.getByRole('button', { name: '重试', exact: true }).click()
    await expect(home.getByRole('alert')).toHaveCount(0)
    expect(await page.evaluate(() => (window as unknown as { __homeQueries: Array<{ cursor?: string }> }).__homeQueries.slice(-2).map(query => query.cursor))).toEqual([undefined, 'next'])
    await expect(detail.locator('pre')).toBeVisible()
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(camera).toBeFocused()
    await search.fill('')
    await expect(home.locator('.debug-home-space .debug-home-objects [data-record-id="camera"]')).toBeVisible()
    await page.screenshot({ path: info.outputPath('home-production-hierarchy.png') })
    await camera.click()
    await detail.getByRole('button', { name: '查看所属空间', exact: true }).click()
    await expect(detail.getByRole('heading')).toHaveText('书房空间')
    await detail.getByRole('button', { name: '查看所属住所', exact: true }).click()
    await expect(detail.getByRole('heading')).toHaveText('住所记录')
    await home.getByRole('button', { name: '备用收纳盒', exact: true }).click()
    await detail.getByText('完整字段', { exact: true }).click()
    await expect(detail).toContainText('displayInHome = false')
    await expect(detail).toContainText('未归置')
    await expect(home.locator('[data-record-id="wrong"]')).toContainText('父级类型不符')
    await expect(home.locator('[data-record-id="wrong"]')).toContainText('陈列标记格式异常')
    await home.getByRole('button', { name: '旧类型记录', exact: true }).click()
    await detail.getByText('来源与原始记录', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('未知原文字段')
    await camera.click()
    await detail.getByRole('button', { name: '来源生活事件', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-recent').getByRole('article', { name: '领域证据详情' })).toContainText('来源事件正文')
    expect(await page.evaluate(() => (window as unknown as { __homeQueries: Array<{ view: string; recordId?: string }> }).__homeQueries.at(-1))).toMatchObject({ view: 'recent', recordId: 'event-real' })
    await nav.getByRole('button', { name: '家居', exact: true }).click()
    await home.getByRole('button', { name: '读取下一页', exact: true }).click()
    await page.evaluate(() => { (window as unknown as { __homeMode: string }).__homeMode = 'orphan' })
    await panel.getByRole('button', { name: '刷新当前分区', exact: true }).click()
    await expect(home.locator('[data-record-id="camera"]')).toContainText('父级未在当前已读范围')
    await camera.click()
    await detail.getByRole('button', { name: '查看空间引用', exact: true }).click()
    await expect(home).toContainText('引用家居未在当前已读人物范围找到，未选择替代记录。')
    await expect(detail).toHaveCount(0)
    await home.getByRole('button', { name: '返回当前领域列表', exact: true }).click()
    await page.evaluate(() => { (window as unknown as { __homeMode: string }).__homeMode = 'long' })
    await panel.getByRole('button', { name: '刷新当前分区', exact: true }).click()
    await home.getByRole('button', { name: '住所记录', exact: true }).click()
    await expect(detail.locator('.debug-home-body')).toHaveText('家居长描述。'.repeat(200))
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await home.locator('.debug-home-name').first().evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('home-production-detail.png') })
    await home.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(home).toContainText('不推断默认住所或世界状态')
    await expect(home.locator('[data-record-id]')).toHaveCount(0)
  })
}
