import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 746]) {
  test(`输入边界候选 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => localStorage.setItem('theme', theme), theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const nav = page.getByTestId('playground-nav')
    await expect(page.getByTestId('playground-product-nav')).toHaveCount(0)
    await expect(nav.getByText('产品入口', { exact: true })).toHaveCount(0)
    await nav.getByRole('button', { name: '人物世界', exact: true }).click()
    await expect(page.getByTestId('world-tab-wardrobe')).toBeVisible()
    await nav.getByRole('button', { name: '设置', exact: true }).click()
    await expect(page.getByTestId('settings-main')).toBeVisible()
    await nav.getByRole('button', { name: '基础组件', exact: true }).click()
    await page.getByRole('tab', { name: '按钮', exact: true }).click()
    for (const selector of ['.foundation-action-button', '.foundation-button']) {
      const button = page.locator(selector).filter({ visible: true }).first()
      await button.scrollIntoViewIfNeeded()
      await expect(button).toHaveCSS('border-radius', '6px')
      const before = await button.boundingBox()
      await button.hover()
      await button.focus()
      expect(await button.boundingBox()).toEqual(before)
    }
    await expect(page.locator('.playground-story-block').first()).toHaveCSS('border-radius', '16px')
    await page.getByRole('tab', { name: '卡片', exact: true }).click()
    for (const card of await page.locator('[data-shape="card"]').all()) await expect(card).toHaveCSS('border-radius', '16px')
    await page.getByRole('tab', { name: '弹层', exact: true }).click()
    await page.getByRole('button', { name: '打开对话框', exact: true }).click()
    await expect(page.getByRole('dialog', { name: '确认清理样张' })).toHaveCSS('border-radius', '22px')
    await page.getByRole('button', { name: '关闭对话框', exact: true }).click()
    await page.getByRole('tab', { name: '输入与表单', exact: true }).click()
    const fields = ['基础输入默认', '超长内容输入', '带图标输入', '显示名称', '错误字段']
    for (const name of fields) {
      const scope = ['显示名称', '错误字段'].includes(name) ? page.getByTestId('foundation-story-form-field') : page
      const field = scope.getByRole('textbox', { name, exact: true })
      await field.scrollIntoViewIfNeeded()
      await field.blur()
      const radius = await field.evaluate(node => getComputedStyle(node).getPropertyValue('--radius-md').trim())
      await expect(field).toHaveCSS('border-top-width', '1px')
      await expect(field).toHaveCSS('border-top-left-radius', radius)
      const before = await field.boundingBox()
      await field.hover()
      expect(await field.boundingBox()).toEqual(before)
      await field.focus()
      await expect(field).toHaveCSS('box-shadow', 'none')
      expect(await field.boundingBox()).toEqual(before)
      await field.fill('测试输入')
      await expect(field).toHaveValue('测试输入')
      await field.evaluate(node => (node as HTMLInputElement).disabled = true)
      expect(await field.boundingBox()).toEqual(before)
      await field.evaluate(node => (node as HTMLInputElement).disabled = false)
    }
    const form = page.getByTestId('foundation-story-form-field')
    const error = form.getByRole('textbox', { name: '错误字段', exact: true })
    await error.blur()
    const errorColor = await error.evaluate(node => getComputedStyle(node).borderColor)
    await error.focus()
    await expect(error).toHaveCSS('border-color', errorColor)
    expect(errorColor).not.toBe(await form.getByRole('textbox', { name: '显示名称', exact: true }).evaluate(node => getComputedStyle(node).borderColor))
    await error.evaluate(node => (node as HTMLElement).style.setProperty('--radius-input', '14px'))
    await expect(error).toHaveCSS('border-radius', '14px')
    await error.evaluate(node => (node as HTMLElement).style.removeProperty('--radius-input'))
    await page.screenshot({ path: info.outputPath('input-fields.png'), fullPage: true })
    await page.getByRole('tab', { name: '标签与选择', exact: true }).click()
    await expect(page.getByRole('combobox', { name: '搜索伙伴' })).toHaveCSS('border-top-width', '1px')
    await page.getByRole('tab', { name: '菜单与提示', exact: true }).click()
    const embedded = page.getByRole('textbox', { name: '搜索动作', exact: true })
    await embedded.scrollIntoViewIfNeeded()
    await embedded.focus()
    await expect(embedded).toHaveCSS('border-top-width', '0px')
    await expect(embedded).toHaveCSS('box-shadow', 'none')
    await embedded.fill('打开')
    await expect(embedded).toHaveValue('打开')
    expect(await page.getByTestId('playground-main').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await nav.getByRole('button', { name: '返回', exact: true }).click()
    await expect(page.getByTestId('primary-sidebar')).toBeVisible()
  })
}

