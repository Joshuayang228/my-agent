import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`关联 v3 单边与定位 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '生活事件关联', exact: true }).click()
    const links = panel.getByTestId('debug-evidence-links')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const detail = links.getByRole('article', { name: '领域证据详情' })
    const search = links.getByRole('textbox', { name: '搜索当前页证据' })
    const camera = links.locator('[data-record-id="demo-link-reading"]').getByRole('button')
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '关联边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    const filters = links.locator('.debug-links-filter')
    const openFilters = async () => { if (await filters.getAttribute('open') === null) await filters.locator('summary').click() }
    await expect(detail).toHaveCount(0)
    await expect(links.locator('[data-record-id]')).toHaveCount(5)
    await expect(links.locator('[data-event-key="demo-event-reading"] [data-record-id]')).toHaveCount(4)
    await expect(camera).toHaveCSS('font-size', '14px')
    await expect(camera).toContainText('保存名')
    await expect(camera).toHaveCSS('color', await links.evaluate(node => getComputedStyle(node).color))
    const contrast = await links.locator('.debug-links-meta').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / scale).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const color = getComputedStyle(node).color
      const surface = getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor
      const fg = luminance(color), bg = luminance(surface)
      return { color, surface, ratio: (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05) }
    })
    expect(contrast.ratio, JSON.stringify(contrast)).toBeGreaterThanOrEqual(4.5)
    await page.screenshot({ path: info.outputPath('links-v3-default.png') })
    await camera.click()
    await expect(detail.locator('.debug-links-edge')).toContainText('demo-item-camera')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('"relation": "references"')
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(camera).toBeFocused()
    expect((await links.locator('[data-record-id="demo-link-image"] .debug-links-meta code').innerText()).length).toBeLessThan(40)
    await links.locator('[data-record-id="demo-link-image"]').getByRole('button').click()
    await expect(detail.locator('.debug-links-edge')).toContainText('aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa')
    await expect(detail).toContainText('当前响应未提供目标定位')
    await expect(detail.getByRole('button', { name: '查看明确关联的资产', exact: true })).toHaveCount(0)
    await expect(detail.locator('img')).toHaveCount(0)
    await edge('metadata-shape')
    await expect(links.locator('[data-record-id]')).toHaveCount(5)
    await camera.click()
    await expect(detail).toContainText('元数据不是对象，原始值保留')
    await edge('no-jumps')
    await camera.click()
    await expect(detail).toContainText('当前响应未提供事件定位')
    await expect(detail.locator('.debug-links-actions button')).toHaveCount(0)
    await edge('paged')
    await expect(links.locator('[data-record-id]')).toHaveCount(2)
    await search.fill('demo-yu')
    await expect(links.getByRole('status')).toContainText('没有匹配的关联')
    await links.getByRole('button', { name: '读取下一页关联样张', exact: true }).click()
    await expect(links.locator('.debug-links-range')).toContainText('1 项匹配 · 5 条已读关联')
    await links.locator('[data-record-id="demo-link-cast"]').getByRole('button').click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(search).toHaveValue('demo-yu')
    await expect(detail.locator('.debug-links-edge')).toContainText('demo-yu')
    await links.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await search.fill('')
    await openFilters()
    await links.getByRole('combobox', { name: '关联目标类型' }).selectOption('image')
    await expect(links.locator('[data-record-id]')).toHaveCount(1)
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(links.getByRole('combobox', { name: '关联目标类型' })).toHaveValue('image')
    await links.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await links.getByRole('combobox', { name: '关联目标类型' }).selectOption('all')
    await links.getByLabel('关联创建日', { exact: true }).fill('2026-10-12')
    await expect(links.locator('[data-record-id]')).toHaveCount(1)
    await expect(links.getByRole('button', { name: '读取下一页关联样张', exact: true })).toHaveCount(0)
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(links.getByLabel('关联创建日', { exact: true })).toHaveValue('2026-10-12')
    await links.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await links.getByLabel('关联创建日', { exact: true }).fill('')
    await filters.locator('summary').click()
    await edge('unknown-time')
    await camera.click()
    await detail.getByText('完整字段', { exact: true }).click()
    await expect(detail.locator('.debug-candidate-facts')).toContainText('关联创建时间未记录')
    await expect(detail).not.toContainText('1970')
    await edge('unknown')
    await openFilters()
    await links.getByRole('combobox', { name: '关联目标类型' }).selectOption('unknown')
    await expect(links.locator('[data-record-id]')).toHaveCount(1)
    await links.getByRole('combobox', { name: '关联目标类型' }).selectOption('all')
    await filters.locator('summary').click()
    await edge('partial')
    await expect(links.getByRole('status')).toContainText('一条关联记录格式不可读取')
    await expect(links.locator('[data-record-id]')).toHaveCount(4)
    await edge('truncated')
    await camera.click()
    await expect(detail).toContainText('不能认定元数据完整')
    await links.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(links.getByRole('status')).toContainText('不推断事件从未有关联')
    await links.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(links.locator('[data-record-id]')).toHaveCount(0)
      await expect(links.locator('.debug-links-range')).toHaveCount(0)
    }
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(search).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(links.getByRole('alert')).toContainText('关联记录读取失败')
    await links.getByRole('button', { name: '读取关联样张', exact: true }).click()
    await edge('missing')
    await expect(detail).toHaveCount(0)
    await expect(links.getByRole('status')).toContainText('未选择替代记录')
    await edge('long')
    await camera.click()
    expect((await camera.innerText()).length).toBeLessThan(110)
    const bodies = detail.locator('.debug-links-body')
    expect((await bodies.first().innerText()).length).toBeGreaterThan(800)
    expect((await bodies.last().innerText()).length).toBeGreaterThan(1000)
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await bodies.last().evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('links-v3-long.png') })
    await camera.click()
    await detail.getByRole('button', { name: '查看明确关联的资产', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-residence').getByRole('article', { name: '领域证据详情' })).toContainText('小相机')
    await nav.getByRole('button', { name: '生活事件关联', exact: true }).click()
    await camera.click()
    await detail.getByRole('button', { name: '查看来源事件', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-recent').getByRole('article', { name: '领域证据详情' })).toContainText('没有完成证据')
  })
}
