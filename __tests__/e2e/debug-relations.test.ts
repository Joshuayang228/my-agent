import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`通讯录 v3 关系方向与共同事件 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '通讯录', exact: true }).click()
    const contacts = panel.getByTestId('debug-evidence-relations')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const detail = contacts.getByRole('article', { name: '领域证据详情' })
    const search = contacts.getByRole('textbox', { name: '搜索当前页证据' })
    const person = contacts.locator('[data-record-id="demo-relation-yu"]').getByRole('button')
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '关系边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(detail).toHaveCount(0)
    await expect(contacts.locator('[data-record-id]')).toHaveCount(2)
    await expect(person).toHaveCSS('font-size', '14px')
    await expect(contacts).not.toContainText('忙碌')
    await expect(contacts).not.toContainText('首次共同整理资料')
    const contrast = await contacts.locator('.debug-relations-meta').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / scale).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const color = getComputedStyle(node).color
      const surface = getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor
      const fg = luminance(color), bg = luminance(surface)
      return { color, surface, ratio: (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05) }
    })
    expect(contrast.ratio, JSON.stringify(contrast)).toBeGreaterThanOrEqual(4.5)
    await page.screenshot({ path: info.outputPath('relations-v3-default.png') })
    await person.click()
    await expect(detail.locator('.debug-relations-definition')).toHaveCount(2)
    await expect(detail.locator('.debug-relations-definition').first()).toContainText('林 · 样张 → 予 · 样张')
    await expect(detail.locator('.debug-relations-definition').last()).toContainText('予 · 样张 → 林 · 样张')
    await expect(detail.locator('.debug-relations-definition').last()).toContainText('反方向关系定义样张')
    await detail.getByText('共同在场的事件', { exact: true }).click()
    await expect(detail.locator('.debug-relations-experience')).toHaveCount(2)
    await expect(detail).toContainText('不是完整交往历史')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(detail.locator('.debug-relations-experience').first()).toBeVisible()
    await contacts.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(person).toBeFocused()
    await search.fill('旧书')
    await expect(contacts.locator('[data-record-id]')).toHaveCount(1)
    await person.click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(search).toHaveValue('旧书')
    await expect(detail).toBeVisible()
    await contacts.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await search.fill('')
    await contacts.locator('[data-record-id="demo-relation-user"]').getByRole('button').click()
    await detail.getByText('共同在场的事件', { exact: true }).click()
    await expect(detail).toContainText('本次已读范围没有共同在场事件')
    await contacts.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await contacts.getByRole('button', { name: '查看人物：林 · 样张', exact: true }).click()
    await expect(detail).toContainText('本次查询未提供共同经历，数量未知')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(contacts.getByRole('combobox', { name: '诊断人物' })).toHaveValue('yu')
    await contacts.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await contacts.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    await edge('same-name')
    await expect(contacts.getByRole('button', { name: '查看人物：予 · 样张', exact: true })).toHaveCount(2)
    await contacts.locator('[data-record-id="demo-relation-user"]').getByRole('button').click()
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('demo-user')
    await expect(detail.locator('pre')).not.toContainText('demo-yu')
    await edge('unregistered')
    await expect(person).toHaveText('demo-yu')
    await edge('missing-note')
    await expect(contacts.locator('[data-record-id="demo-relation-yu"]')).toContainText('关系说明未提供')
    await edge('no-experience-source')
    await person.click()
    await detail.getByText('共同在场的事件', { exact: true }).click()
    await expect(detail).toContainText('本次查询未提供共同经历')
    await edge('unknown-time')
    await expect(detail).toContainText('事件计划时间：未记录')
    await expect(detail).not.toContainText('1970')
    await edge('experience-error')
    await expect(contacts.getByRole('status')).toContainText('一条共同经历格式损坏')
    await expect(detail.locator('.debug-relations-definition')).toHaveCount(2)
    await expect(detail.locator('.debug-relations-experience')).toHaveCount(1)
    await expect(detail.locator('.debug-relations-experience')).toContainText('整理旧书')
    await edge('truncated')
    await expect(detail).toContainText('以下仅含已返回内容')
    await edge('limited')
    await expect(contacts.locator('.debug-relations-range')).toContainText('1 位已读人物 · 总数未知')
    await expect(contacts.getByRole('button', { name: /下一页/ })).toHaveCount(0)
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(contacts.locator('[data-record-id]')).toHaveCount(1)
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(contacts.locator('[data-record-id]')).toHaveCount(0)
      await expect(contacts.locator('.debug-relations-range')).toHaveCount(0)
    }
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(search).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(contacts.getByRole('alert')).toContainText('关系资料读取失败')
    await contacts.getByRole('button', { name: '读取关系样张', exact: true }).click()
    await edge('missing')
    await expect(detail).toHaveCount(0)
    await expect(contacts.getByRole('status')).toContainText('未选择替代记录')
    await edge('long')
    await person.click()
    expect((await detail.locator('.debug-relations-definition .debug-relations-body').first().innerText()).length).toBeGreaterThan(400)
    expect((await contacts.locator('[data-record-id="demo-relation-yu"] .debug-relations-meta').first().innerText()).length).toBeLessThan(150)
    await detail.getByText('共同在场的事件', { exact: true }).click()
    expect((await detail.locator('.debug-relations-experience .debug-relations-body').first().innerText()).length).toBeGreaterThan(1000)
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await detail.locator('.debug-relations-definition .debug-relations-body').first().evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('relations-v3-long.png') })
    await states.getByRole('button', { name: '默认记录', exact: true }).click()
    await person.click()
    await detail.locator('.debug-relations-experience').first().getByRole('button', { name: '查看共同事件来源', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-recent').getByRole('article', { name: '领域证据详情' })).toContainText('没有完成证据')
    await nav.getByRole('button', { name: '通讯录', exact: true }).click()
    await person.click()
    await detail.getByRole('button', { name: '查看成长与反思', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-growth').getByRole('article', { name: '领域证据详情' })).toHaveCount(0)
    await nav.getByRole('button', { name: '通讯录', exact: true }).click()
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(contacts.getByRole('status')).toContainText('不推断没有关系')
  })
}
