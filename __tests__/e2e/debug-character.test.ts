import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`人物档案 v3 资料与缺口 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '人物档案', exact: true }).click()
    const character = panel.getByTestId('debug-evidence-character')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const toggle = character.getByRole('button', { name: /完整资料/ })
    const detail = character.getByRole('article', { name: '领域证据详情' })
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '人物资料边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
      if (await toggle.count() && await toggle.getAttribute('aria-expanded') === 'true') await toggle.click()
    }
    await expect(character.locator('.debug-character-body')).toHaveCSS('font-size', '14px')
    await expect(character.locator('.debug-character-facts > div')).toHaveCount(3)
    await expect(detail).toHaveCount(0)
    expect(await character.getByRole('combobox').evaluate(node => node.getBoundingClientRect().width)).toBeLessThanOrEqual(180)
    await page.screenshot({ path: info.outputPath('character-v3-default.png') })
    await toggle.click()
    await expect(detail.getByRole('heading', { name: '人物定义', exact: true })).toBeVisible()
    await expect(detail.locator('.debug-character-profile')).toContainText('局限')
    await expect(detail.locator('.debug-character-profile')).toContainText('表达基线')
    await detail.getByText('默认世界定义', { exact: true }).click()
    await expect(detail).toContainText('不等于当前世界为空')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('schemaVersion')
    await detail.getByRole('button', { name: /查看注册定义/ }).first().click()
    await expect(panel).toHaveAttribute('data-perspective', 'assets')
    await expect(panel).toContainText('demo.role.lin')
    await nav.getByRole('button', { name: '人物档案', exact: true }).click()
    await toggle.click()
    await detail.getByRole('button', { name: '查看成长与反思', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-growth').getByRole('article', { name: '领域证据详情' })).toHaveCount(0)
    await nav.getByRole('button', { name: '人物档案', exact: true }).click()
    await character.getByRole('combobox').selectOption('yu')
    await expect(character.getByRole('status')).toContainText('详细人物资料未提供')
    await expect(character.locator('.debug-character-body')).toContainText('予的简介')
    await toggle.click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(detail).toBeVisible()
    await expect(character.getByRole('combobox')).toHaveValue('yu')
    await expect(character.getByRole('alert')).toContainText('保留上次资料')
    await character.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await character.getByRole('combobox').selectOption('lin')
    await edge('empty-profile')
    await expect(character.getByRole('status')).toContainText('空资料结构')
    await edge('partial')
    await expect(character.locator('.debug-character-facts')).toContainText('未提供')
    await toggle.click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(character.locator('.debug-character-facts')).not.toContainText('生活记录者')
    await expect(detail).toBeVisible()
    for (const value of ['unavailable', 'error', 'missing']) {
      await edge(value)
      await expect(character.locator('[data-record-id]')).toHaveCount(0)
      await expect(character.getByRole(value === 'missing' ? 'status' : 'alert')).toBeVisible()
    }
    await states.getByRole('button', { name: '运行中', exact: true }).click()
    await expect(character.getByRole('status')).toHaveText('正在读取人物资料…')
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(character.getByRole('combobox')).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(character.getByRole('alert')).toContainText('人物资料读取失败')
    await expect(character.locator('[data-record-id]')).toHaveCount(0)
    await character.getByRole('button', { name: '读取资料样张', exact: true }).click()
    await edge('long')
    expect((await character.locator('.debug-character-summary .debug-character-body').innerText()).length).toBeLessThanOrEqual(161)
    await toggle.click()
    expect((await detail.locator('.debug-character-body').innerText()).length).toBeGreaterThan(600)
    await expect(detail.locator('.debug-character-profile')).toContainText('额外资料字段也完整保留')
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await character.locator('.debug-character-summary .debug-character-body').evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('character-v3-long.png') })
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(character.getByRole('status')).toContainText('未补造人物设定')
  })
}
