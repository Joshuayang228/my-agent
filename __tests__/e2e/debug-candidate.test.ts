import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1280, 600]) {
  test(`Debug 证据浏览 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.addInitScript(theme => {
      localStorage.setItem('theme', theme)
      localStorage.setItem('playground.active-tab', 'debug')
    }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation', { name: 'Debug 候选导航' })
    await expect(page.getByTestId('playground-nav')).toHaveCount(0)
    await expect(panel.getByTestId('debug-call-detail')).toContainText('历史正文未保存')
    const runNav = nav.getByRole('button', { name: '运行记录', exact: true })
    const initialBox = await runNav.boundingBox()
    await runNav.hover()
    await runNav.focus()
    expect(await runNav.boundingBox()).toEqual(initialBox)
    expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('debug-overview.png') })
    await panel.getByRole('button', { name: '查看实际来源' }).click()
    await panel.getByRole('button', { name: /主对话语义编译/ }).click()
    await expect(panel.getByRole('article', { name: '资产详情' })).toContainText('demo.prompt.main')
    await page.screenshot({ path: info.outputPath('debug-assets.png') })
    await panel.getByRole('button', { name: /读取旅行记录 demo-call-02/ }).click()
    await expect(panel.getByTestId('debug-call-detail')).toContainText('demo-call-02')
    await panel.getByRole('button', { name: '执行过程', exact: true }).click()
    await expect(panel.getByTestId('debug-call-detail')).toContainText('权限检查')
    await page.screenshot({ path: info.outputPath('debug-execution.png') })
    await panel.getByRole('button', { name: /提取旅行偏好/ }).click()
    await panel.getByRole('button', { name: '执行过程', exact: true }).click()
    await expect(panel).toContainText('没有关联的执行证据')
    await panel.getByRole('textbox', { name: '搜索运行记录' }).fill('no-such-request')
    await expect(panel).toContainText('没有匹配的记录')
    await panel.getByRole('button', { name: '清除筛选' }).click()
    await panel.getByRole('group', { name: '调用状态筛选' }).getByRole('button', { name: '失败', exact: true }).click()
    await expect(panel.getByRole('button', { name: /读取旅行记录/ })).toHaveCount(0)
    await panel.getByRole('group', { name: '调用状态筛选' }).getByRole('button', { name: '全部', exact: true }).click()
    await panel.getByRole('group', { name: 'Debug 样张状态' }).getByRole('button', { name: '运行中', exact: true }).click()
    await expect(panel.getByTestId('debug-call-detail')).toContainText('最终耗时待定')
    await panel.getByRole('group', { name: 'Debug 样张状态' }).getByRole('button', { name: '刷新失败' }).click()
    await expect(panel).toContainText('刷新失败，保留上次证据')
    await expect(panel.getByTestId('debug-call-detail')).toContainText('demo-call-03')
    await expect(panel.getByTestId('debug-call-detail')).toContainText('最终耗时待定')
    await panel.getByRole('button', { name: '重试读取样张' }).click()
    await expect(panel).not.toContainText('刷新失败，保留上次证据')
    await panel.getByRole('group', { name: 'Debug 样张状态' }).getByRole('button', { name: '无记录' }).click()
    await expect(panel).toContainText('还没有运行记录')
    await panel.getByRole('group', { name: 'Debug 样张状态' }).getByRole('button', { name: '默认记录' }).click()
    await nav.getByRole('button', { name: '质量报告', exact: true }).click()
    await panel.getByText('查看失败检查证据').click()
    await expect(panel).toContainText('样张期望：仅可读取')
    await page.screenshot({ path: info.outputPath('debug-quality.png') })
    await panel.getByRole('button', { name: /人格一致性验收/ }).click()
    await expect(panel).toContainText('当前样张尚无人工结论')
    await nav.getByRole('button', { name: '伙伴状态', exact: true }).click()
    await expect(panel).toContainText('当前状态，非历史请求')
    await nav.getByRole('button', { name: '系统状态', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(panel).toContainText('工具清单尚未取得，数量未知')
    await panel.getByRole('button', { name: '返回 Playground' }).click()
    await expect(page.getByTestId('playground-nav')).toBeVisible()
  })
}
