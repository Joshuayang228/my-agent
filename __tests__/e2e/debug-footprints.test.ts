import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`足迹 v3 日期与状态 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    await panel.getByRole('navigation').getByRole('button', { name: '足迹', exact: true }).click()
    const trips = panel.getByTestId('debug-evidence-footprints')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const search = trips.getByRole('textbox', { name: '搜索当前页证据' })
    const detail = trips.getByRole('article', { name: '领域证据详情' })
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '足迹边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(trips.locator('[data-record-id]')).toHaveCount(5)
    await expect(trips.locator('[data-travel-group="actual"] [data-record-id]')).toHaveCount(2)
    await expect(trips.locator('[data-travel-group="actual"] [data-record-id]').first()).toHaveAttribute('data-record-id', 'demo-trip-active')
    await expect(trips.getByRole('button', { name: '河边旅行', exact: true })).toHaveCSS('font-size', '14px')
    await expect(trips.getByRole('button', { name: '河边旅行', exact: true })).toHaveCSS('color', await trips.evaluate(node => getComputedStyle(node).color))
    const contrast = await trips.locator('.debug-travel-meta').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / scale).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const color = getComputedStyle(node).color
      const surface = getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor
      const fg = luminance(color), bg = luminance(surface)
      return { color, surface, ratio: (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05) }
    })
    expect(contrast.ratio, JSON.stringify(contrast)).toBeGreaterThanOrEqual(4.5)
    await expect(detail).toHaveCount(0)
    await expect(trips).not.toContainText('停留经历样张')
    await page.screenshot({ path: info.outputPath('footprints-v3-default.png') })
    await search.fill('河边步道')
    await expect(trips.locator('[data-record-id]')).toHaveCount(1)
    await trips.getByRole('button', { name: '河边旅行', exact: true }).click()
    await expect(detail.getByRole('heading', { name: '2026-10-10 · 河边步道', exact: true })).toBeVisible()
    await expect(detail.locator('.debug-travel-stop')).toContainText('停留经历样张')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('demo-stop-river')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(search).toHaveValue('河边步道')
    await expect(detail).toBeVisible()
    await trips.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(trips.getByRole('button', { name: '河边旅行', exact: true })).toBeFocused()
    await search.fill('')
    await edge('unknown')
    await expect(trips.locator('[data-travel-group="unknown"] [data-record-id="demo-trip-completed"]')).toBeVisible()
    await expect(trips.locator('[data-travel-group="actual"] [data-record-id]')).toHaveCount(1)
    await edge('undated')
    await expect(trips.locator('.debug-travel-list')).not.toContainText('2026-10-13')
    await expect(trips.locator('[data-record-id="demo-trip-completed"]')).toContainText('资料不完整')
    await trips.getByRole('button', { name: '河边旅行', exact: true }).click()
    await expect(detail.getByRole('heading', { name: '日期未提供 · 河边步道', exact: true })).toBeVisible()
    await expect(detail).toContainText('不据此确认实际出发')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(detail.getByRole('heading', { name: '日期未提供 · 河边步道', exact: true })).toBeVisible()
    await edge('paged')
    await expect(trips.locator('[data-record-id]')).toHaveCount(2)
    await search.fill('海边')
    await expect(trips.getByRole('status')).toContainText('没有匹配的足迹')
    await trips.getByRole('button', { name: '读取下一页样张', exact: true }).click()
    await expect(trips.locator('.debug-travel-range')).toHaveText('1 项匹配 · 5 项已读 · 总数未知')
    await trips.getByRole('button', { name: '海边旅行计划', exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(trips.locator('.debug-travel-range')).toContainText('5 项已读')
    await expect(detail).toContainText('不纳入实际旅行')
    await trips.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await expect(trips.getByRole('button', { name: '读取下一页样张', exact: true })).toHaveCount(0)
    await search.fill('')
    await trips.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(trips.getByRole('status')).toContainText('不推断人物从未到访')
    await trips.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(trips.locator('[data-record-id]')).toHaveCount(0)
      await expect(trips.locator('.debug-travel-range')).toHaveCount(0)
    }
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(search).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(trips.getByRole('alert')).toContainText('足迹读取失败')
    await expect(trips.locator('.debug-travel-range')).toHaveCount(0)
    await trips.getByRole('button', { name: '读取足迹样张', exact: true }).click()
    await edge('missing')
    await expect(detail).toHaveCount(0)
    await expect(trips.getByRole('status')).toContainText('未选择替代记录')
    await edge('long')
    await trips.getByRole('button', { name: /河边旅行/ }).click()
    expect((await detail.locator(':scope > .debug-travel-body').innerText()).length).toBeGreaterThan(1000)
    expect((await detail.locator('.debug-travel-stop').innerText()).length).toBeGreaterThan(800)
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await trips.locator('.debug-travel-name').first().evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('footprints-v3-long.png') })
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(trips.getByRole('status')).toContainText('没有已读取足迹资产')
  })
}
