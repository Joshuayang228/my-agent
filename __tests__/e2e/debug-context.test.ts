import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`上下文 v3 保存范围 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '上下文', exact: true }).click()
    const context = panel.getByTestId('debug-evidence-context')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '上下文边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(context).toContainText('全局调用范围')
    await expect(context.getByRole('combobox', { name: '诊断人物' })).toHaveCount(0)
    await expect(context.locator('.debug-context-message')).toHaveCount(8)
    await expect(context.locator('.debug-context-message').first()).toContainText('1 · system')
    await expect(context).toContainText('保存长度 2400 字符')
    await expect(context.locator('.debug-context-picker select')).toHaveCSS('font-size', '13px')
    await expect(context).toHaveCSS('font-size', '14px')
    const ratio = await context.locator('.debug-context-caption').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const v = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(n => n / scale).map(n => n <= 0.04045 ? n / 12.92 : ((n + 0.055) / 1.055) ** 2.4)
        return v[0] * 0.2126 + v[1] * 0.7152 + v[2] * 0.0722
      }
      const fg = luminance(getComputedStyle(node).color), bg = luminance(getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor)
      return (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05)
    })
    expect(ratio).toBeGreaterThanOrEqual(4.5)
    await page.screenshot({ path: info.outputPath('context-v3-default.png') })
    await context.getByRole('button', { name: '显示其余 4 条消息', exact: true }).click()
    await expect(context.locator('.debug-context-message')).toHaveCount(12)
    const first = context.locator('.debug-context-message').first()
    await first.locator(':scope > summary').click()
    await first.getByText('完整消息结构', { exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(context.locator('.debug-context-message')).toHaveCount(12)
    await expect(first.locator('pre')).toBeVisible()
    await context.getByRole('tab', { name: '工具', exact: true }).click()
    await expect(context.getByRole('region', { name: '保存的工具' })).toContainText('不代表当前可执行权限')
    await expect(context.getByRole('region', { name: '保存的工具' })).toContainText('demo_read')
    await context.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await expect(context.getByRole('tab', { name: '工具', exact: true })).toHaveAttribute('aria-selected', 'true')
    await context.getByRole('combobox', { name: '选择保存的调用' }).selectOption('demo-call-01')
    await expect(context).toContainText('已保存工具列表为空')
    await context.getByRole('tab', { name: '请求参数', exact: true }).click()
    await expect(context.getByRole('region', { name: '保存的请求参数' })).toContainText('不是当前模型配置')
    await context.getByText('来源与完整保存结构', { exact: true }).click()
    await expect(context.locator('.debug-context-source')).toContainText('demo-session-02')
    await context.getByRole('button', { name: '查看这次调用', exact: true }).click()
    await expect(panel.getByTestId('debug-call-detail')).toContainText('demo-call-01')
    await nav.getByRole('button', { name: '上下文', exact: true }).click()
    await edge('detail-error')
    await expect(context).toContainText('详情读取失败')
    await expect(context.locator('.debug-context-message')).toHaveCount(0)
    await context.getByRole('button', { name: '重试详情样张' }).click()
    await expect(context.locator('.debug-context-message')).toHaveCount(8)
    await edge('missing')
    await expect(context).toContainText('未选择其他调用代替')
    await expect(context.getByRole('article')).toHaveCount(0)
    await edge('malformed')
    await expect(context).toContainText('消息结构不是数组')
    await context.getByText('来源与完整保存结构', { exact: true }).click()
    await expect(context.locator('.debug-context-source pre')).toContainText('unexpected')
    await edge('no-system')
    await context.getByRole('tab', { name: '消息', exact: true }).click()
    await expect(context).toContainText('未返回独立 System 消息')
    await edge('empty-input')
    await expect(context).toContainText('0 条已保存消息结构')
    await expect(context.locator('.debug-context-message')).toHaveCount(0)
    await edge('long')
    await context.locator('.debug-context-message > summary').click()
    await expect(context.locator('.debug-context-body')).toHaveText('【历史内容样张】这是旧记录中返回的虚构文字，不是当前提示词。\n'.repeat(90))
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await context.evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await context.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('context-v3-long.png') })
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(context.locator('.debug-context-message')).toHaveCount(0)
      await expect(context).not.toContainText('条已保存消息结构')
    }
    await states.getByRole('button', { name: '历史截断', exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(context).toContainText('不代表全部调用历史')
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(context).toContainText('调用清单读取失败')
    await expect(context).not.toContainText('条已保存消息结构')
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(context).toContainText('当前查询没有调用记录')
  })
}
