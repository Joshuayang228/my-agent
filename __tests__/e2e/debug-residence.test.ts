import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`家居 v3 归属与快照 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    await panel.getByRole('navigation').getByRole('button', { name: '家居', exact: true }).click()
    const home = panel.getByTestId('debug-evidence-residence')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const search = home.getByRole('textbox', { name: '搜索当前页证据' })
    const detail = home.getByRole('article', { name: '领域证据详情' })
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '家居边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(home.locator('[data-record-id]')).toHaveCount(4)
    await expect(home.locator('.debug-home-space .debug-home-objects [data-record-id="demo-item-camera"]')).toBeVisible()
    await expect(home.getByRole('button', { name: '小相机', exact: true })).toHaveCSS('font-size', '14px')
    await expect(home.getByRole('button', { name: '小相机', exact: true })).toHaveCSS('color', await home.evaluate(node => getComputedStyle(node).color))
    const contrast = await home.locator('.debug-home-description').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / scale).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const color = getComputedStyle(node).color
      const surface = getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor
      const foreground = luminance(color)
      const background = luminance(surface)
      return { color, surface, ratio: (Math.max(foreground, background) + 0.05) / (Math.min(foreground, background) + 0.05) }
    })
    expect(contrast.ratio, JSON.stringify(contrast)).toBeGreaterThanOrEqual(4.5)
    await expect(detail).toHaveCount(0)
    await page.screenshot({ path: info.outputPath('residence-v3-default.png') })
    await search.fill('小相机')
    await expect(home.locator('[data-record-id]')).toHaveCount(1)
    await expect(home.locator('.debug-home-meta')).toContainText('归属：空间')
    await home.getByRole('button', { name: '小相机', exact: true }).click()
    await expect(detail.locator('.debug-home-body')).toContainText('日常整理旅行照片')
    await detail.getByText('完整字段', { exact: true }).click()
    await expect(detail).toContainText('displayInHome = true')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(search).toHaveValue('小相机')
    await expect(detail).toBeVisible()
    await expect(home.getByRole('alert')).toContainText('保留上次资产')
    await home.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(home.getByRole('button', { name: '小相机', exact: true })).toBeFocused()
    await search.fill('')
    await home.getByRole('button', { name: '小相机', exact: true }).click()
    await detail.getByRole('button', { name: '查看所属空间', exact: true }).click()
    await expect(detail.getByRole('heading')).toHaveText('空间 · 样张书房')
    await detail.getByRole('button', { name: '查看所属住所', exact: true }).click()
    await expect(detail.getByRole('heading')).toHaveText('住所 · 样张住所')
    await home.getByRole('button', { name: '备用收纳盒', exact: true }).click()
    await detail.getByText('完整字段', { exact: true }).click()
    await expect(detail).toContainText('displayInHome = false')
    await expect(detail).toContainText('空间未归置')
    await edge('orphan')
    await expect(home.locator('[data-record-id="demo-item-camera"]')).toContainText('父级未在当前已读范围')
    await home.getByRole('button', { name: '小相机', exact: true }).click()
    await expect(detail.getByRole('button', { name: '查看关联生活事件', exact: true })).toBeVisible()
    await detail.getByRole('button', { name: '查看所属空间', exact: true }).click()
    await expect(detail).toHaveCount(0)
    await expect(home.getByRole('status')).toContainText('未选择替代记录')
    await edge('unknown-display')
    await expect(home.locator('[data-record-id="demo-item-camera"]')).toContainText('陈列标记未记录')
    await home.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(home.getByRole('status')).toContainText('不推断默认住所')
    await home.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    await edge('paged')
    await expect(home.locator('[data-record-id]')).toHaveCount(2)
    await home.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(home.getByRole('button', { name: '读取下一页样张', exact: true })).toHaveCount(0)
    await home.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    await search.fill('小相机')
    await expect(home.getByRole('status')).toContainText('没有匹配的家居')
    await home.getByRole('button', { name: '读取下一页样张', exact: true }).click()
    await expect(home.locator('.debug-home-range')).toHaveText('1 项匹配 · 4 项已读 · 总数未知')
    await home.getByRole('button', { name: '小相机', exact: true }).click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(home.locator('.debug-home-range')).toContainText('4 项已读')
    await expect(detail).toBeVisible()
    await home.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await expect(home.locator('.debug-home-range')).toContainText('4 项已读')
    await expect(home.getByRole('button', { name: '读取下一页样张', exact: true })).toHaveCount(0)
    await search.fill('')
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(home.locator('[data-record-id]')).toHaveCount(0)
      await expect(home.locator('.debug-home-range')).toHaveCount(0)
    }
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(search).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(home.getByRole('alert')).toContainText('家居资料读取失败')
    await expect(home.locator('.debug-home-range')).toHaveCount(0)
    await home.getByRole('button', { name: '读取家居样张', exact: true }).click()
    await edge('long')
    await home.locator('.debug-home-residence > article').getByRole('button').click()
    expect((await detail.locator('.debug-home-body').innerText()).length).toBeGreaterThan(1000)
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('家居长描述样张')
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await home.locator('.debug-home-name').first().evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('residence-v3-long.png') })
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(home.getByRole('status')).toContainText('没有已读取家居资产')
  })
}
