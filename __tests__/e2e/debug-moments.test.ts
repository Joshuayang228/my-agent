import { test, expect } from '@playwright/test'

for (const theme of ['porcelain-blue', 'yao-stone']) for (const width of [1096, 600]) {
  test(`朋友圈 v3 发布与互动 ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 704 })
    await page.addInitScript(theme => { localStorage.setItem('theme', theme); localStorage.setItem('playground.active-tab', 'debug') }, theme)
    await page.goto('/')
    await page.getByTestId('primary-sidebar').getByRole('button', { name: 'Playground', exact: true }).click()
    const panel = page.getByTestId('debug-candidate')
    const nav = panel.getByRole('navigation')
    await nav.getByRole('button', { name: '朋友圈', exact: true }).click()
    const moments = panel.getByTestId('debug-evidence-moments')
    const states = panel.getByRole('group', { name: 'Debug 样张状态' })
    const detail = moments.getByRole('article', { name: '领域证据详情' })
    const search = moments.getByRole('textbox', { name: '搜索当前页证据' })
    const date = moments.getByLabel('动态发布日', { exact: true })
    const reading = moments.locator('[data-record-id="demo-moment-reading"]').getByRole('button')
    const edge = async (value: string) => {
      await states.getByText('更多样张', { exact: true }).click()
      await states.getByRole('combobox', { name: '动态边缘样张' }).selectOption(value)
      await states.getByText('更多样张', { exact: true }).click()
    }
    await expect(detail).toHaveCount(0)
    await expect(moments.locator('[data-record-id]')).toHaveCount(3)
    await expect(moments.locator('[data-record-id]').first()).toHaveAttribute('data-record-id', 'demo-moment-evening')
    await expect(reading).toHaveCSS('font-size', '14px')
    await expect(moments).not.toContainText('同框记录')
    const contrast = await moments.locator('.debug-moments-meta').first().evaluate(node => {
      const luminance = (color: string) => {
        const scale = color.startsWith('color(srgb ') ? 1 : 255
        const [r, g, b] = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / scale).map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        return r * 0.2126 + g * 0.7152 + b * 0.0722
      }
      const color = getComputedStyle(node).color
      const surface = getComputedStyle(document.querySelector('.debug-candidate')!).backgroundColor
      const fg = luminance(color), bg = luminance(surface)
      return { color, surface, ratio: (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05) }
    })
    expect(contrast.ratio, JSON.stringify(contrast)).toBeGreaterThanOrEqual(4.5)
    await page.screenshot({ path: info.outputPath('moments-v3-default.png') })
    await reading.click()
    await expect(detail.locator(':scope > .debug-moments-body')).toContainText('翻到上次旅途')
    await expect(detail.getByText('同框记录', { exact: false })).not.toBeVisible()
    await detail.getByText('互动记录', { exact: true }).click()
    await expect(detail).toContainText('予 · 同框记录')
    await expect(detail).toContainText('予 · 评论')
    await expect(detail).toContainText('我 · 点赞')
    await expect(detail).toContainText('用户评论样张')
    await detail.getByText('来源与原始样张', { exact: true }).click()
    await expect(detail.locator('pre')).toContainText('demo-event-reading')
    await detail.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(reading).toBeFocused()
    await moments.locator('[data-record-id="demo-moment-evening"]').getByRole('button').click()
    await detail.getByText('互动记录', { exact: true }).click()
    await expect(detail).toContainText('本次查询未提供用户互动，数量未知')
    await moments.locator('[data-record-id="demo-moment-book"]').getByRole('button').click()
    await expect(detail).toContainText('本次已读范围没有用户互动')
    await edge('paged')
    await expect(moments.locator('[data-record-id]')).toHaveCount(1)
    await search.fill('车票')
    await expect(moments.getByRole('status')).toContainText('没有匹配的动态')
    await moments.getByRole('button', { name: '读取下一页动态样张', exact: true }).click()
    await expect(moments.locator('.debug-moments-range')).toContainText('1 项匹配 · 3 项已读动态')
    await moments.locator('[data-record-id="demo-moment-book"]').getByRole('button').click()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(search).toHaveValue('车票')
    await expect(detail.locator(':scope > .debug-moments-body')).toContainText('车票')
    await expect(moments.locator('.debug-moments-range')).toContainText('3 项已读动态')
    await moments.getByRole('button', { name: '重试读取样张', exact: true }).click()
    await search.fill('')
    await date.fill('2026-10-12')
    await expect(moments.locator('[data-record-id]')).toHaveCount(1)
    await expect(moments.getByRole('button', { name: '读取下一页动态样张', exact: true })).toHaveCount(0)
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(date).toHaveValue('2026-10-12')
    await moments.getByRole('combobox', { name: '诊断人物' }).selectOption('yu')
    await expect(moments.getByRole('status')).toContainText('不据此推断人物从未发布')
    await expect(moments.getByRole('button', { name: '读取下一页动态样张', exact: true })).toHaveCount(0)
    await moments.getByRole('combobox', { name: '诊断人物' }).selectOption('lin')
    await date.fill('')
    await edge('unknown-time')
    await expect(moments.locator('[data-record-id="demo-moment-reading"]')).toContainText('发布：未记录')
    await date.fill('2026-10-13')
    await expect(moments.locator('[data-record-id="demo-moment-reading"]')).toHaveCount(0)
    await date.fill('')
    await edge('empty-body')
    await moments.getByRole('button', { name: '查看动态：动态正文为空', exact: true }).click()
    await expect(detail).toContainText('未补事件文案')
    await edge('truncated')
    await reading.click()
    await expect(detail).toContainText('互动总数未知')
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(detail).toContainText('记录读取有截断')
    await edge('partial')
    await expect(moments.locator('[data-record-id]')).toHaveCount(2)
    await expect(moments.getByRole('status')).toContainText('一条动态记录格式不可读取')
    for (const value of ['unavailable', 'error']) {
      await edge(value)
      await expect(moments.locator('[data-record-id]')).toHaveCount(0)
      await expect(moments.locator('.debug-moments-range')).toHaveCount(0)
    }
    await states.getByRole('button', { name: '未读取', exact: true }).click()
    await expect(search).toBeDisabled()
    await states.getByRole('button', { name: '刷新失败', exact: true }).click()
    await expect(moments.getByRole('alert')).toContainText('动态读取失败')
    await moments.getByRole('button', { name: '读取动态样张', exact: true }).click()
    await edge('missing')
    await expect(detail).toHaveCount(0)
    await expect(moments.getByRole('status')).toContainText('未选择替代记录')
    await edge('long')
    await reading.click()
    const body = await detail.locator(':scope > .debug-moments-body').innerText()
    expect(body.length).toBeGreaterThan(1000)
    expect(body.length).toBeLessThanOrEqual(8000)
    expect((await reading.innerText()).length).toBeLessThanOrEqual(141)
    await detail.getByText('互动记录', { exact: true }).click()
    const comment = detail.locator('.debug-moments-interaction .debug-moments-body').last()
    expect((await comment.innerText()).length).toBeLessThanOrEqual(280)
    await expect(comment).toContainText('用户长评论样张')
    for (const scale of ['sm', 'lg']) {
      await page.evaluate(scale => document.documentElement.setAttribute('data-font-scale', scale), scale)
      expect(await detail.locator(':scope > .debug-moments-body').evaluate(node => parseFloat(getComputedStyle(node).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))).toBeCloseTo(14 / 15, 3)
      expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    }
    await page.evaluate(() => document.documentElement.setAttribute('data-font-scale', 'md'))
    await page.screenshot({ path: info.outputPath('moments-v3-long.png') })
    await states.getByRole('button', { name: '默认记录', exact: true }).click()
    await reading.click()
    await detail.getByRole('button', { name: '查看发布来源事件', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-recent').getByRole('article', { name: '领域证据详情' })).toContainText('没有完成证据')
    await nav.getByRole('button', { name: '朋友圈', exact: true }).click()
    await reading.click()
    await detail.getByRole('button', { name: '查看生活事件关联', exact: true }).click()
    await expect(panel.getByTestId('debug-evidence-links').getByRole('article', { name: '领域证据详情' })).toHaveCount(0)
    await nav.getByRole('button', { name: '朋友圈', exact: true }).click()
    await states.getByRole('button', { name: '无记录', exact: true }).click()
    await expect(moments.getByRole('status')).toContainText('没有已读动态')
  })
}
